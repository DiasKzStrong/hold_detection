"""A static gallery: open index.html directly, without a web service."""

from html import escape
import json
from pathlib import Path
from urllib.parse import quote
from zipfile import ZIP_DEFLATED, ZipFile

from PIL import Image, ImageDraw

from ..capture.images import processed_image


ROUTE_COLORS = (
    "#ef4444", "#3b82f6", "#22c55e", "#f59e0b", "#a855f7",
    "#06b6d4", "#ec4899", "#84cc16", "#f97316", "#6366f1",
)


SIGNATURE = "<!-- Generated by DeMoSearch holds gallery -->"


def asset_url(root: Path, frame: Path, value: str) -> str:
    target = (frame / value).resolve()
    if not target.is_relative_to(root.resolve()):
        raise ValueError("Gallery asset escapes the run directory")
    return quote(target.relative_to(root.resolve()).as_posix(), safe="/")


def write_color_overlay(frame_path: Path, frame: dict) -> None:
    image = processed_image(frame)
    overlay = image.copy()
    draw = ImageDraw.Draw(overlay)
    for hold in frame["holds"]:
        candidate_id = hold.get("route_candidate_id")
        if not candidate_id:
            continue
        route_number = int(candidate_id.rsplit("_", 1)[1])
        color = ROUTE_COLORS[(route_number - 1) % len(ROUTE_COLORS)]
        if mask_path := hold.get("mask_path"):
            with Image.open(frame_path.parent / mask_path) as stored_mask:
                mask = stored_mask.convert("L")
            tint = Image.new("RGB", image.size, color)
            alpha = mask.point(lambda value: 78 if value else 0)
            overlay = Image.composite(tint, overlay, alpha)
            draw = ImageDraw.Draw(overlay)
        x1, y1, x2, y2 = hold["bbox_xyxy"]
        draw.rectangle((x1, y1, x2, y2), outline=color, width=3)
        label = f"{hold['hold_id']}  {candidate_id}"
        anchor = (x1, max(0, y1 - 14))
        bounds = draw.textbbox(anchor, label)
        draw.rectangle(bounds, fill="black")
        draw.text(anchor, label, fill=color)
    overlay.save(frame_path.parent / "routes.jpg", quality=95)


def build_gallery(run: Path, *, include_scene: bool = True) -> Path:
    summary = json.loads((run / "summary.json").read_text())
    target = run / "index.html"
    if target.exists() and not target.read_text().startswith(SIGNATURE):
        raise FileExistsError(f"Refusing to replace a non-generated gallery: {target}")
    sections = []
    frame_paths = sorted(run.glob("*/holds.json"))
    if len(frame_paths) != summary["frame_count"]:
        raise ValueError("Run is incomplete: frame JSON count differs from summary")
    for frame_path in frame_paths:
        if not frame_path.resolve().is_relative_to(run.resolve()):
            raise ValueError("Gallery frame escapes the run directory")
        frame = json.loads(frame_path.read_text())
        title = escape(Path(frame["source_image"]).name)
        annotation = asset_url(run, frame_path.parent, "annotated.jpg")
        route_review = (
            asset_url(run, frame_path.parent, "routes.jpg")
            if (frame_path.parent / "routes.jpg").is_file() else None
        )
        details = []
        for hold in frame["holds"]:
            label = hold["object_kind"]
            if hold.get("hold_type"):
                label += " · " + hold["hold_type"]
            score_text = f'detection score {hold["detector_score"]:.2f}'
            reasons = ", ".join(hold["review_reasons"])
            review = " · REVIEW: " + reasons if reasons else ""
            crop = asset_url(run, frame_path.parent, hold["crop_path"])
            mask = (f'<a href="{asset_url(run, frame_path.parent, hold["mask_path"])}">mask PNG</a>'
                    if hold.get("mask_path") else "no mask")
            route = hold.get("route_candidate_id") or "unassigned"
            swatch = hold.get("median_rgb")
            swatch_html = (
                f'<span class="swatch" style="background:rgb({swatch[0]},{swatch[1]},{swatch[2]})"></span>'
                if swatch else ""
            )
            details.append(
                f'<article class="hold" data-review="{str(hold["needs_review"]).lower()}">'
                f'<a href="{crop}"><img loading="lazy" src="{crop}" alt="hold crop"></a>'
                f'<p>{escape(hold["hold_id"])} · {escape(label)}<br>'
                f'{swatch_html}{escape(route)}<br>{score_text}'
                f'<br><span class="review">{escape(review)}</span><br>{mask}</p></article>'
            )
        frame_json = asset_url(run, frame_path.parent, "holds.json")
        sections.append(
            f'<section><h2>{title}</h2><p>{len(frame["holds"])} candidates · '
            f'<a href="{frame_json}">JSON</a></p>'
            + (f'<h3>Route review</h3><a href="{route_review}"><img class="wall" loading="lazy" '
               f'src="{route_review}" alt="Color-grouped routes"></a>' if route_review else '')
            + '<h3>Detection review</h3>'
            + f'<a href="{annotation}"><img class="wall" loading="lazy" '
            f'src="{annotation}" alt="Annotated wall"></a>'
            f'<details><summary>Show observation evidence</summary><div class="crops">'
            + "".join(details) + '</div></details></section>'
        )
    html = SIGNATURE + """<!doctype html>
<html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>DeMoSearch results</title><style>
body{font:16px system-ui;margin:24px auto;padding:0 18px;max-width:1300px;background:#171a20;color:#e8eaf0}
a{color:#87c6ff}header{margin-bottom:24px}section{border-top:1px solid #454954;padding:20px 0}
.wall{max-width:100%;max-height:850px}summary{cursor:pointer;padding:14px 0}
.crops{display:grid;grid-template-columns:repeat(auto-fill,minmax(170px,1fr));gap:12px}
.hold{background:#242933;padding:10px;overflow-wrap:anywhere}.hold img{width:100%;height:140px;object-fit:contain}
.hold p{font-size:13px}.review{color:#ffc773}.swatch{display:inline-block;width:12px;height:12px;border:1px solid #fff;margin-right:6px;vertical-align:-1px}body.review-only .hold[data-review="false"]{display:none}
</style><header><h1>DeMoSearch results</h1>"""
    scene_link = '<p><a href="scene.json">Download scene.json</a></p>' if include_scene and (run / "scene.json").is_file() else ""
    html += (f'<p>{summary["frame_count"]} frames · {summary["detection_count"]} candidate observations · '
             f'masks {"enabled" if summary["segmentation_enabled"] else "disabled"}</p>'
             + scene_link
             + '<p>Repeated views and false positives are included. Scores are not calibrated accuracy.</p>'
             '<label><input type="checkbox" onchange="document.body.classList.toggle(\'review-only\',this.checked)"> '
             'Show only review crops</label></header>' + "".join(sections) + '</html>')
    target.write_text(html, encoding="utf-8")
    return target


def bundle_results(run: Path, destination: Path) -> Path:
    """Package a completed run or experiment for offline review."""
    if destination.resolve().is_relative_to(run.resolve()):
        raise ValueError("Save the result ZIP outside the run directory")
    destination.parent.mkdir(parents=True, exist_ok=True)
    with ZipFile(destination, "x", compression=ZIP_DEFLATED) as z:
        for path in sorted(run.rglob("*")):
            if path.is_symlink():
                raise ValueError("Do not bundle symlinks in a result directory")
            if path.is_file():
                if not path.resolve().is_relative_to(run.resolve()):
                    raise ValueError("Result file escapes its run directory")
                z.write(path, arcname=run.name + "/" + path.relative_to(run).as_posix())
    return destination
